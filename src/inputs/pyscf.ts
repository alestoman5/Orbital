// PySCF script generator: InputSpec -> a runnable, commented Python 3 script
// in the style of uv-vis scripts/run_adc.py (argparse with the spec's values
// as defaults, thread variables set before numpy is imported, atomic
// result.json, exit code 1 when anything did not converge). Pure string
// logic, no Node / DOM / vscode imports.
//
// result.json always has: program, program_version, method, basis, charge,
// multiplicity, task, converged, energies {scf, total, ...}, time_<step>_s.
// Excited-state scripts add excitation_energies_ev, oscillator_strengths and
// time_adc_s (the key the Calculations tab / src/chem/neaRun.ts reads for the
// excited-state step, whatever the method).

import { formatAtomLines } from '../chem/inputFile';
import { functionalInfo, solventInfo } from './catalog';
import {
  InputSpec, SpecIssue, describeSpec, effectiveDispersion, effectiveReference, hasFrequencies, isAdc,
  isOptimization, isTsSearch, validateSpec
} from './spec';

export interface GeneratedScript {
  text: string;
  warnings: string[];
  errors: string[];
  issues: SpecIssue[];
  /** pip packages the script imports (pyscf first). */
  requires: string[];
}

const py = (s: string) => JSON.stringify(s); // a JSON string literal is a valid Python str literal
const pyBool = (b: boolean) => (b ? 'True' : 'False');

/** libxc name used by PySCF for the spec's functional. */
export function pyscfXc(spec: InputSpec): string {
  return functionalInfo(spec.method.functional)?.pyscf ?? spec.method.functional.trim().toLowerCase();
}

/** Density fitting for the SCF? auto = DFT only (HF references of ADC/CC stay exact, as in run_adc.py). */
export function pyscfDensityFit(spec: InputSpec): boolean {
  if (spec.ri.mode === 'none') {
    return false;
  }
  if (spec.ri.mode === 'auto') {
    return spec.method.family === 'dft';
  }
  return true;
}

export function pyscfRequires(spec: InputSpec): string[] {
  const req = ['pyscf'];
  if (isOptimization(spec.job)) {
    req.push('geometric');
  }
  if (effectiveDispersion(spec) !== 'none' || /d3|d4/.test(spec.method.family === 'dft' ? pyscfXc(spec) : '')) {
    req.push('pyscf-dispersion');
  }
  return req;
}

function methodLabel(spec: InputSpec): string {
  const exc = spec.excited.method;
  if (isAdc(exc)) {
    return ''; // taken from --method at run time
  }
  if (exc === 'eom-ccsd') {
    return 'eom-ee-ccsd';
  }
  if (exc === 'tddft') {
    return spec.method.family === 'hf' ? (spec.excited.tda ? 'cis' : 'tdhf') : (spec.excited.tda ? 'tda' : 'tddft');
  }
  return spec.method.family;
}

const ADC_METHOD: Record<string, string> = { adc2: 'adc(2)', adc2x: 'adc(2)-x', adc3: 'adc(3)' };

function errorScript(spec: InputSpec, errors: string[]): string {
  return [
    '#!/usr/bin/env python3',
    `# ${spec.title || 'PySCF job'}`,
    '# Orbital Studio could not generate this PySCF script:',
    ...errors.map(e => `#   - ${e}`),
    'raise SystemExit("not generated, see the comments above")',
    ''
  ].join('\n');
}

function indent(lines: string[], n = 4): string[] {
  const pad = ' '.repeat(n);
  return lines.map(l => (l ? pad + l : l));
}

export function buildPyscfScript(spec: InputSpec): GeneratedScript {
  const issues = validateSpec(spec, 'pyscf');
  const errors = issues.filter(i => i.severity === 'error').map(i => `${i.path}: ${i.message}`);
  const warnings = issues.filter(i => i.severity === 'warning').map(i => `${i.path}: ${i.message}`);
  const requires = pyscfRequires(spec);
  if (errors.length > 0) {
    return { text: errorScript(spec, errors), warnings, errors, issues, requires };
  }

  const fam = spec.method.family;
  const exc = spec.excited.method;
  const ref = effectiveReference(spec);
  const job = spec.job;
  const opt = isOptimization(job) && job !== 'scan';
  const freq = hasFrequencies(job);
  const correlated = fam !== 'hf' && fam !== 'dft';
  const needsCore = (correlated && fam !== 'casscf' && fam !== 'nevpt2') || isAdc(exc) || exc === 'eom-ccsd';
  const cas = fam === 'casscf' || fam === 'nevpt2';
  const solv = spec.solvation.model;
  const solvent = solventInfo(spec.solvation.solvent);
  const disp = effectiveDispersion(spec);
  const xyzDefault = spec.geometry.xyzFile?.trim();

  // ------------------------------------------------------------------ header
  const out: string[] = [];
  out.push('#!/usr/bin/env python3');
  const doc: string[] = [`${spec.title || 'PySCF job'}`, '', `${describeSpec(spec)}. Generated by Orbital Studio; edit freely.`];
  if (spec.comment.trim()) {
    doc.push('', ...spec.comment.trim().split(/\r?\n/).map(l => l.trimEnd()));
  }
  const usage = ['python run.py', xyzDefault ? `[${xyzDefault}]` : '[geom.xyz]', '[result.json]'];
  if (exc !== 'none') {
    usage.push('[--nstates N]');
  }
  usage.push('[--basis B]', '[--threads N]', '[--memory MB]');
  doc.push('', `  ${usage.join(' ')}`, '');
  doc.push(xyzDefault
    ? `The geometry is read from ${xyzDefault} (Angstrom) unless another .xyz file is given.`
    : 'Without an .xyz argument the inline GEOMETRY below (Angstrom) is used.');
  doc.push(
    'result.json is written atomically, also when a step fails; the exit code is 1 if the SCF',
    'or any later step did not converge.',
    `Requires: pip install ${requires.join(' ')}`
  );
  out.push(`"""${doc.join('\n').replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"')}`, '"""');
  out.push('import argparse', 'import json', 'import os', 'import socket', 'import sys', 'import time', '');
  out.push('HARTREE_TO_EV = 27.211386245988');
  if (!xyzDefault) {
    out.push('', '# Angstrom; used when no .xyz file is given on the command line',
      'GEOMETRY = """', ...formatAtomLines(spec.geometry.atoms), '"""');
  }
  if (job === 'scan') {
    const kind = { B: 'distance', A: 'angle', D: 'dihedral' }[spec.scan.coordinate];
    out.push('',
      `# Scanned coordinate, geomeTRIC constraint syntax (1-based atoms; Angstrom / degrees).`,
      `# Atoms ${spec.scan.atoms.join(' ')} in ORCA's 0-based numbering.`,
      `SCAN_COORD = ${py(`${kind} ${spec.scan.atoms.map(i => i + 1).join(' ')}`)}`);
  }

  // ------------------------------------------------------------------ helpers
  out.push('', '',
    'def write_json(path, data):',
    '    with open(path + ".tmp", "w") as fh:',
    '        json.dump(data, fh, indent=2)',
    '    os.replace(path + ".tmp", path)   # atomic: a half-written result.json must never look done',
    '', '',
    'def read_xyz(path):',
    '    with open(path) as fh:',
    '        lines = fh.read().splitlines()',
    '    atoms = [(s, (float(x), float(y), float(z))) for s, x, y, z in',
    '             (line.split()[:4] for line in lines[2:2 + int(lines[0])])]',
    '    return atoms, lines[1].strip()');
  if (isOptimization(job)) {
    out.push('', '',
      'def write_xyz(path, mol, comment="", mode="w"):',
      '    xyz = mol.atom_coords(unit="Angstrom")',
      '    with open(path, mode) as fh:',
      '        fh.write(f"{mol.natm}\\n{comment}\\n")',
      '        for i in range(mol.natm):',
      '            fh.write(f"{mol.atom_pure_symbol(i):<3}{xyz[i, 0]:15.8f}{xyz[i, 1]:15.8f}{xyz[i, 2]:15.8f}\\n")');
  }

  // ------------------------------------------------------------------ main(): arguments
  const m: string[] = [];
  m.push('p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)');
  m.push(xyzDefault
    ? `p.add_argument("geom", nargs="?", default=${py(xyzDefault)}, help=".xyz file (Angstrom)")`
    : 'p.add_argument("geom", nargs="?", default=None, help=".xyz file (Angstrom); default: the inline GEOMETRY")');
  m.push('p.add_argument("out", nargs="?", default="result.json")');
  m.push(`p.add_argument("--basis", default=${py(spec.basis.trim())})`);
  if (fam === 'dft') {
    m.push(`p.add_argument("--xc", default=${py(pyscfXc(spec))}, help="exchange-correlation functional (libxc name)")`);
  }
  m.push(`p.add_argument("--charge", type=int, default=${spec.charge})`);
  m.push(`p.add_argument("--mult", type=int, default=${spec.multiplicity}, help="spin multiplicity 2S+1")`);
  if (exc !== 'none') {
    m.push(`p.add_argument("--nstates", type=int, default=${spec.excited.nroots}, help="number of excited states")`);
  }
  if (exc === 'tddft') {
    m.push(`p.add_argument("--tda", action=argparse.BooleanOptionalAction, default=${pyBool(spec.excited.tda)}, help="Tamm-Dancoff approximation")`);
  }
  if (exc === 'tddft' || exc === 'eom-ccsd') {
    m.push(`p.add_argument("--triplets", action=argparse.BooleanOptionalAction, default=${pyBool(spec.excited.triplets)}, help="also compute triplet states")`);
  }
  if (isAdc(exc)) {
    m.push(`p.add_argument("--method", default=${py(ADC_METHOD[exc])}, choices=["adc(2)", "adc(2)-x", "adc(3)"])`);
    m.push('p.add_argument("--max-space", type=int, default=None, help="larger Davidson space, for roots that did not converge")');
  }
  if (needsCore) {
    m.push(`p.add_argument("--frozen-core", action=argparse.BooleanOptionalAction, default=${pyBool(spec.frozenCore)})`);
  }
  if (cas) {
    m.push(`p.add_argument("--nel", type=int, default=${spec.cas.nel}, help="active electrons")`);
    m.push(`p.add_argument("--norb", type=int, default=${spec.cas.norb}, help="active orbitals")`);
    m.push(`p.add_argument("--nroots", type=int, default=${spec.cas.nroots}, help="state-averaged roots")`);
  }
  if (solv === 'cpcm') {
    m.push(`p.add_argument("--eps", type=float, default=${solvent!.eps}, help="dielectric constant (${solvent!.label})")`);
  } else if (solv === 'smd') {
    m.push(`p.add_argument("--solvent", default=${py(solvent!.smd)}, help="SMD solvent name (Minnesota table)")`);
  }
  if (isOptimization(job)) {
    m.push('p.add_argument("--max-steps", type=int, default=100, help="geomeTRIC iterations")');
  }
  if (job === 'scan') {
    m.push(`p.add_argument("--scan-start", type=float, default=${spec.scan.start})`);
    m.push(`p.add_argument("--scan-end", type=float, default=${spec.scan.end})`);
    m.push(`p.add_argument("--scan-points", type=int, default=${spec.scan.points})`);
  }
  if (freq) {
    m.push(`p.add_argument("--temperature", type=float, default=${spec.freq.temperature}, help="K")`);
    m.push(`p.add_argument("--pressure", type=float, default=${spec.freq.pressureAtm * 101325}, help="Pa")`);
  }
  m.push(`p.add_argument("--threads", type=int, default=${spec.resources.nprocs})`);
  m.push(`p.add_argument("--memory", type=int, default=${spec.resources.nprocs * spec.resources.maxcoreMB}, help="MB for the whole process")`);
  m.push('a = p.parse_args()', '');

  // ------------------------------------------------------------------ imports
  m.push('# thread pools are sized when numpy is imported, so this has to come first',
    'for var in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS"):',
    '    os.environ[var] = str(a.threads)',
    'import numpy as np',
    'import pyscf');
  const mods = new Set<string>(['gto', 'lib', fam === 'dft' ? 'dft' : 'scf']);
  if (isAdc(exc)) mods.add('adc');
  if (fam === 'mp2') mods.add('mp');
  if (fam === 'ccsd' || fam === 'ccsd(t)' || exc === 'eom-ccsd') mods.add('cc');
  if (cas) mods.add('mcscf');
  if (fam === 'nevpt2') mods.add('mrpt');
  m.push(`from pyscf import ${[...mods].sort().join(', ')}`);
  if (needsCore) m.push('from pyscf.data import elements');
  if (exc === 'eom-ccsd') m.push('from pyscf.cc import eom_rccsd');
  if (isOptimization(job)) m.push('from pyscf.geomopt import geometric_solver');
  if (freq) m.push('from pyscf.hessian import thermo');
  m.push('');

  // ------------------------------------------------------------------ molecule
  m.push('if a.geom:',
    '    atoms, comment = read_xyz(a.geom)',
    'else:',
    `    atoms, comment = ${xyzDefault ? 'None, ""' : 'GEOMETRY, "inline geometry"'}`,
    'mol = gto.M(atom=atoms, basis=a.basis, charge=a.charge, spin=a.mult - 1, unit="Angstrom",',
    '            max_memory=a.memory, verbose=4)',
    'lib.num_threads(a.threads)',
    ...(isOptimization(job) ? ['workdir = os.path.dirname(os.path.abspath(a.out))   # optimized.xyz etc. go next to result.json'] : []),
    `result = {"program": "pyscf", "program_version": pyscf.__version__, "method": ${isAdc(exc) ? 'a.method' : py(methodLabel(spec))},`,
    `          "basis": a.basis, "charge": a.charge, "multiplicity": a.mult, "task": ${py(job)},`,
    '          "geometry_file": os.path.abspath(a.geom) if a.geom else None, "geometry_comment": comment,',
    '          "host": socket.gethostname(), "converged": False, "energies": {}}');
  if (fam === 'dft') {
    m.push('result["xc"] = a.xc');
  }
  m.push('',
    'def finish(converged, failure=None):',
    '    """Write result.json (always) and exit with code 1 if something did not converge."""',
    '    result["converged"] = bool(converged)',
    '    if failure:',
    '        result["failure"] = failure',
    '    write_json(a.out, result)',
    '    if not converged:',
    '        sys.exit(failure or "not converged")',
    '');

  // ------------------------------------------------------------------ make_scf
  const scfClass = (() => {
    if (fam === 'dft') {
      return { restricted: 'dft.RKS', unrestricted: 'dft.UKS', 'restricted-open': 'dft.ROKS' }[ref] + '(mol, xc=a.xc)';
    }
    return { restricted: 'scf.RHF', unrestricted: 'scf.UHF', 'restricted-open': 'scf.ROHF' }[ref] + '(mol)';
  })();
  m.push('def make_scf(mol):',
    '    """Mean-field object with every setting of this job (reused at new geometries)."""',
    `    mf = ${scfClass}`);
  if (pyscfDensityFit(spec)) {
    m.push('    mf = mf.density_fit()   # density fitting (RI) for J and K, auxiliary basis chosen by PySCF');
  }
  if (disp !== 'none') {
    m.push(`    mf.disp = ${py(disp)}   # needs pip install pyscf-dispersion`);
  }
  if (solv === 'cpcm') {
    m.push('    mf = mf.PCM()',
      '    mf.with_solvent.method = "C-PCM"',
      `    mf.with_solvent.eps = a.eps   # ${solvent!.label}`);
  } else if (solv === 'smd') {
    m.push('    mf = mf.SMD()',
      '    mf.with_solvent.solvent = a.solvent');
  }
  const tol = { normal: '', tight: '1e-10', verytight: '1e-12' }[spec.convergence.scf];
  if (tol) {
    m.push(`    mf.conv_tol = ${tol}`);
  }
  m.push('    mf.max_cycle = 200', '    return mf', '');

  // ------------------------------------------------------------------ SCF
  m.push('t0 = time.perf_counter()',
    'mf = make_scf(mol)',
    'e_scf = mf.kernel()',
    'result["time_scf_s"] = time.perf_counter() - t0',
    'result["energies"]["scf"] = result["energies"]["total"] = float(e_scf)',
    'result["nbf"] = int(mol.nao_nr())',
    'result["nelectron"] = int(mol.nelectron)',
    'if not mf.converged:',
    '    finish(False, "SCF did not converge")',
    'converged = True',
    '');
  if (needsCore) {
    m.push('ncore = elements.chemcore(mol) if a.frozen_core else None   # frozen core orbitals',
      'result["n_frozen_core_orbitals"] = int(ncore or 0)', '');
  }

  // ------------------------------------------------------------------ job body
  m.push(...jobBody(spec));

  const extras = spec.extras.pyscf.trim();
  if (extras) {
    m.push('# --- user additions ---', ...extras.split(/\r?\n/).map(l => l.trimEnd()), '');
  }
  m.push('finish(converged, None if converged else "not all steps converged")');

  out.push('', '', 'def main():', ...indent(m), '', '', 'if __name__ == "__main__":', '    main()', '');
  return { text: out.join('\n'), warnings, errors, issues, requires };
}

/** The job-specific part of main() (unindented). */
function jobBody(spec: InputSpec): string[] {
  const b: string[] = [];
  const fam = spec.method.family;
  const exc = spec.excited.method;
  const job = spec.job;
  const restricted = effectiveReference(spec) === 'restricted';

  // --- geometry optimization (also TS) -------------------------------------
  if (job === 'opt' || job === 'opt-freq' || isTsSearch(job)) {
    const conv = { normal: '', tight: ', convergence_set="GAU_TIGHT"', verytight: ', convergence_set="GAU_VERYTIGHT"' }[spec.convergence.opt];
    const ts = isTsSearch(job) ? ', transition=True, hessian="first"' : '';
    b.push(isTsSearch(job)
      ? '# transition-state search: geomeTRIC computes a finite-difference Hessian first and follows its lowest mode'
      : '# geomeTRIC drives the optimization with analytic PySCF gradients',
    't1 = time.perf_counter()',
    `opt_converged, mol = geometric_solver.kernel(mf, maxsteps=a.max_steps${conv}${ts})`,
    'result["time_opt_s"] = time.perf_counter() - t1',
    'result["optimization_converged"] = bool(opt_converged)',
    'write_xyz(os.path.join(workdir, "optimized.xyz"), mol, "optimized with PySCF/geomeTRIC")',
    'result["optimized_geometry_file"] = os.path.join(workdir, "optimized.xyz")',
    'mf = make_scf(mol)   # SCF at the final geometry (energy, Hessian)',
    'e_scf = mf.kernel()',
    'result["energies"]["scf"] = result["energies"]["total"] = float(e_scf)',
    'converged = bool(opt_converged) and mf.converged',
    '');
  }

  // --- relaxed scan ----------------------------------------------------------
  if (job === 'scan') {
    b.push('# relaxed scan: one constrained optimization per point, each started from the previous one',
      'values = np.linspace(a.scan_start, a.scan_end, a.scan_points)',
      'constraints = os.path.join(workdir, "scan_constraints.txt")',
      'trajectory = os.path.join(workdir, "scan_trj.xyz")',
      'open(trajectory, "w").close()',
      'scan = []',
      't1 = time.perf_counter()',
      'for k, value in enumerate(values, 1):',
      '    with open(constraints, "w") as fh:',
      '        fh.write(f"$set\\n{SCAN_COORD} {value:.6f}\\n")',
      '    point_converged, mol = geometric_solver.kernel(make_scf(mol), constraints=constraints, maxsteps=a.max_steps)',
      '    mf_k = make_scf(mol)',
      '    e_k = float(mf_k.kernel())',
      '    point_converged = bool(point_converged) and mf_k.converged',
      '    converged = converged and point_converged',
      '    write_xyz(trajectory, mol, f"point {k}  {SCAN_COORD} = {value:.4f}  E = {e_k:.10f}", mode="a")',
      '    scan.append({"value": float(value), "energy": e_k, "converged": point_converged})',
      '    print(f"scan point {k}/{len(values)}: {value:.4f}  E = {e_k:.10f}  converged = {point_converged}", flush=True)',
      'result["time_scan_s"] = time.perf_counter() - t1',
      'result["scan"] = {"coordinate": SCAN_COORD, "points": scan, "trajectory_file": trajectory}',
      '');
  }

  // --- frequencies -------------------------------------------------------------
  if (hasFrequencies(job)) {
    b.push('# analytic Hessian -> harmonic frequencies and RRHO thermochemistry',
      't2 = time.perf_counter()',
      'hess = mf.Hessian().kernel()',
      'freq = thermo.harmonic_analysis(mf.mol, hess)',
      'th = thermo.thermo(mf, freq["freq_au"], a.temperature, a.pressure)',
      'thermo.dump_normal_mode(mf.mol, freq)',
      'thermo.dump_thermo(mf.mol, th)',
      'result["time_freq_s"] = time.perf_counter() - t2',
      'wn = np.asarray(freq["freq_wavenumber"])',
      'if np.iscomplexobj(wn):   # imaginary modes come back as imaginary numbers: store them as negative',
      '    wn = np.where(np.abs(wn.imag) > 1e-8, -np.abs(wn.imag), wn.real)',
      'n_imag = int((wn < 0).sum())',
      'result["frequencies_cm1"] = wn.tolist()',
      'result["n_imaginary"] = n_imag',
      'result["thermo"] = {"temperature_K": a.temperature, "pressure_Pa": a.pressure,',
      '                    "zpe_hartree": float(th["ZPE"][0]), "enthalpy_hartree": float(th["H_tot"][0]),',
      '                    "gibbs_hartree": float(th["G_tot"][0])}',
      isTsSearch(job)
        ? 'result["is_transition_state"] = n_imag == 1   # a first-order saddle point has exactly one'
        : 'result["is_minimum"] = n_imag == 0',
      '');
  }

  // --- correlated ground states --------------------------------------------------
  if (fam === 'mp2') {
    b.push('t1 = time.perf_counter()',
      'pt = mp.MP2(mf, frozen=ncore)',
      'pt.kernel()',
      'result["time_mp2_s"] = time.perf_counter() - t1',
      'result["energies"]["mp2"] = result["energies"]["total"] = float(pt.e_tot)',
      '');
  }
  if (fam === 'ccsd' || fam === 'ccsd(t)') {
    b.push('t1 = time.perf_counter()',
      'mycc = cc.CCSD(mf, frozen=ncore)',
      'mycc.kernel()',
      'result["time_ccsd_s"] = time.perf_counter() - t1',
      'result["energies"]["ccsd"] = result["energies"]["total"] = float(mycc.e_tot)',
      'if not mycc.converged:',
      '    finish(False, "CCSD did not converge")');
    if (fam === 'ccsd(t)') {
      b.push('t2 = time.perf_counter()',
        'e_t = mycc.ccsd_t()',
        'result["time_t_s"] = time.perf_counter() - t2',
        'result["energies"]["ccsd(t)"] = result["energies"]["total"] = float(mycc.e_tot + e_t)');
    }
    b.push('');
  }
  if (fam === 'casscf' || fam === 'nevpt2') {
    b.push('# active space: (alpha, beta) electrons from --nel and the multiplicity',
      'nelecas = ((a.nel + a.mult - 1) // 2, (a.nel - a.mult + 1) // 2)',
      't1 = time.perf_counter()',
      'mc = mcscf.CASSCF(mf, a.norb, nelecas)',
      'if a.nroots > 1:',
      '    mc.fix_spin_(ss=(a.mult - 1) / 2 * ((a.mult - 1) / 2 + 1))   # keep all roots in the requested spin state',
      '    mc = mc.state_average_([1.0 / a.nroots] * a.nroots)          # equal weights',
      'mc.kernel()',
      'result["time_casscf_s"] = time.perf_counter() - t1',
      'e_cas = [float(e) for e in np.atleast_1d(mc.e_states if a.nroots > 1 else mc.e_tot)]',
      'result["energies"]["casscf"] = result["energies"]["total"] = e_cas[0]',
      'result["casscf_state_energies"] = e_cas',
      'result["active_space"] = {"nel": a.nel, "norb": a.norb, "nroots": a.nroots}',
      'if not mc.converged:',
      '    finish(False, "CASSCF did not converge")',
      'state_energies = e_cas');
    if (fam === 'nevpt2') {
      b.push('# strongly contracted NEVPT2 per root; state-averaged orbitals go through a CASCI first',
        't2 = time.perf_counter()',
        'if a.nroots == 1:',
        '    e_ref, e_corr = [float(mc.e_tot)], [float(mrpt.NEVPT(mc).kernel())]',
        'else:',
        '    mci = mcscf.CASCI(mf, a.norb, nelecas)',
        '    mci.fcisolver.nroots = a.nroots',
        '    mci.fix_spin_(ss=(a.mult - 1) / 2 * ((a.mult - 1) / 2 + 1))',
        '    mci.kernel(mc.mo_coeff)',
        '    e_ref = [float(e) for e in mci.e_tot]',
        '    e_corr = [float(mrpt.NEVPT(mci, root=i).kernel()) for i in range(a.nroots)]',
        'result["time_nevpt2_s"] = time.perf_counter() - t2',
        'state_energies = [r + c for r, c in zip(e_ref, e_corr)]',
        'result["nevpt2_state_energies"] = state_energies',
        'result["energies"]["nevpt2"] = result["energies"]["total"] = state_energies[0]');
    }
    b.push('if len(state_energies) > 1:   # vertical excitations relative to root 0 (no oscillator strengths)',
      '    result["excitation_energies_ev"] = [(e - state_energies[0]) * HARTREE_TO_EV for e in state_energies[1:]]',
      '');
  }

  // --- excited states ----------------------------------------------------------
  if (exc === 'tddft') {
    const hf = fam === 'hf';
    const full = hf ? 'mf.TDHF()' : 'mf.TDDFT()';
    b.push(hf ? '# linear response: TDA (= CIS) or full TDHF (RPA)' : '# linear response: TDA or full TD-DFT',
      'def run_td(singlet):',
      `    td = mf.TDA() if a.tda else ${full}`,
      '    td.nstates = a.nstates');
    if (restricted) {
      b.push('    td.singlet = singlet');
    }
    b.push('    td.kernel()',
      '    conv = [bool(c) for c in np.atleast_1d(td.converged)]',
      '    e_ev = (np.atleast_1d(td.e) * HARTREE_TO_EV).tolist()',
      '    # length gauge; triplets are spin-forbidden (f = 0)',
      '    osc = np.atleast_1d(td.oscillator_strength(gauge="length")).tolist() if singlet else [0.0] * len(e_ev)',
      '    return e_ev, osc, conv',
      '',
      't1 = time.perf_counter()',
      'e_ev, osc, root_conv = run_td(singlet=True)',
      'result["excitation_energies_ev"] = e_ev',
      'result["oscillator_strengths"] = osc',
      'result["osc_gauge"] = "length"',
      'result["roots_converged"] = root_conv',
      'converged = converged and bool(root_conv) and all(root_conv)',
      'if a.triplets:',
      '    e_t, _, conv_t = run_td(singlet=False)',
      '    result["triplet_excitation_energies_ev"] = e_t',
      '    converged = converged and all(conv_t)',
      'result["time_adc_s"] = result["time_excited_s"] = time.perf_counter() - t1   # time_adc_s: read by the Calculations tab',
      'for i, (e, f) in enumerate(zip(e_ev, osc), 1):',
      '    print(f"state {i}: {e:10.6f} eV ({1239.841984 / e:7.2f} nm)  f = {f:.6e}")',
      '');
  }
  if (isAdc(exc)) {
    b.push('# pyscf.adc keeps no per-root convergence flag, so catch the one its Davidson solver returns',
      '# (the last call is the ADC eigenproblem itself)',
      'root_conv = []',
      'davidson = lib.linalg_helper.davidson_nosym1',
      '',
      'def davidson_logged(*args, **kwargs):',
      '    conv, e, u = davidson(*args, **kwargs)',
      '    root_conv[:] = [bool(c) for c in conv]',
      '    return conv, e, u',
      'lib.linalg_helper.davidson_nosym1 = davidson_logged',
      '',
      't1 = time.perf_counter()',
      'myadc = adc.ADC(mf, frozen=ncore)   # frozen is refused after construction',
      'myadc.method = a.method',
      'myadc.method_type = "ee"',
      'myadc.compute_properties = True',
      'myadc.approx_trans_moments = False',
      'myadc.max_memory = a.memory',
      'if a.max_space:',
      '    myadc.max_space = a.max_space',
      'e_exc, _, osc, _ = myadc.kernel(nroots=a.nstates)',
      'result["time_adc_s"] = time.perf_counter() - t1',
      'e_ev = (np.atleast_1d(e_exc) * HARTREE_TO_EV).tolist()',
      'osc = np.atleast_1d(osc).tolist()',
      'result["excitation_energies_ev"] = e_ev',
      'result["oscillator_strengths"] = osc',
      'result["osc_gauge"] = "length"',
      'result["roots_converged"] = list(root_conv)',
      'result["settings"] = {"approx_trans_moments": False, "adc_conv_tol": myadc.conv_tol,',
      '                      "adc_max_space": myadc.max_space, "adc_max_cycle": myadc.max_cycle}',
      'converged = converged and bool(root_conv) and all(root_conv)',
      'for i, (e, f) in enumerate(zip(e_ev, osc), 1):',
      '    print(f"state {i}: {e:10.6f} eV ({1239.841984 / e:7.2f} nm)  f = {f:.6e}")',
      '');
  }
  if (exc === 'eom-ccsd') {
    b.push('t1 = time.perf_counter()',
      'mycc = cc.CCSD(mf, frozen=ncore)',
      'mycc.kernel()',
      'result["time_ccsd_s"] = time.perf_counter() - t1',
      'result["energies"]["ccsd"] = result["energies"]["total"] = float(mycc.e_tot)',
      'if not mycc.converged:',
      '    finish(False, "CCSD did not converge")',
      '',
      '# EOM-EE-CCSD singlets (PySCF gives no transition moments, so no oscillator strengths)',
      't2 = time.perf_counter()',
      'eom = eom_rccsd.EOMEESinglet(mycc)',
      'e_exc, _ = eom.kernel(nroots=a.nstates)',
      'root_conv = [bool(c) for c in np.atleast_1d(eom.converged)]',
      'result["excitation_energies_ev"] = (np.atleast_1d(e_exc) * HARTREE_TO_EV).tolist()',
      'result["roots_converged"] = root_conv',
      'converged = converged and all(root_conv)',
      'if a.triplets:',
      '    eom_t = eom_rccsd.EOMEETriplet(mycc)',
      '    e_t, _ = eom_t.kernel(nroots=a.nstates)',
      '    result["triplet_excitation_energies_ev"] = (np.atleast_1d(e_t) * HARTREE_TO_EV).tolist()',
      '    converged = converged and all(np.atleast_1d(eom_t.converged))',
      'result["time_adc_s"] = result["time_excited_s"] = time.perf_counter() - t2   # time_adc_s: read by the Calculations tab',
      'for i, e in enumerate(result["excitation_energies_ev"], 1):',
      '    print(f"state {i}: {e:10.6f} eV ({1239.841984 / e:7.2f} nm)")',
      '');
  }
  return b;
}
