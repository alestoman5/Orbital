#!/usr/bin/env python3
"""Opt + Freq for Wigner sampling

opt + freq: PBE0-D3BJ/def2-TZVP. Generated by Orbital Studio; edit freely.

  python run.py [geom.xyz] [result.json] [--basis B] [--threads N] [--memory MB]

Without an .xyz argument the inline GEOMETRY below (Angstrom) is used.
result.json is written atomically, also when a step fails; the exit code is 1 if the SCF
or any later step did not converge.
Requires: pip install pyscf geometric pyscf-dispersion
"""
import argparse
import json
import os
import socket
import sys
import time

HARTREE_TO_EV = 27.211386245988

# Angstrom; used when no .xyz file is given on the command line
GEOMETRY = """
O       0.00000000     0.00000000     0.11730000
H       0.00000000     0.75720000    -0.46920000
H       0.00000000    -0.75720000    -0.46920000
"""


def write_json(path, data):
    with open(path + ".tmp", "w") as fh:
        json.dump(data, fh, indent=2)
    os.replace(path + ".tmp", path)   # atomic: a half-written result.json must never look done


def read_xyz(path):
    with open(path) as fh:
        lines = fh.read().splitlines()
    atoms = [(s, (float(x), float(y), float(z))) for s, x, y, z in
             (line.split()[:4] for line in lines[2:2 + int(lines[0])])]
    return atoms, lines[1].strip()


def write_xyz(path, mol, comment="", mode="w"):
    xyz = mol.atom_coords(unit="Angstrom")
    with open(path, mode) as fh:
        fh.write(f"{mol.natm}\n{comment}\n")
        for i in range(mol.natm):
            fh.write(f"{mol.atom_pure_symbol(i):<3}{xyz[i, 0]:15.8f}{xyz[i, 1]:15.8f}{xyz[i, 2]:15.8f}\n")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("geom", nargs="?", default=None, help=".xyz file (Angstrom); default: the inline GEOMETRY")
    p.add_argument("out", nargs="?", default="result.json")
    p.add_argument("--basis", default="def2-TZVP")
    p.add_argument("--xc", default="pbe0", help="exchange-correlation functional (libxc name)")
    p.add_argument("--charge", type=int, default=0)
    p.add_argument("--mult", type=int, default=1, help="spin multiplicity 2S+1")
    p.add_argument("--max-steps", type=int, default=100, help="geomeTRIC iterations")
    p.add_argument("--temperature", type=float, default=298.15, help="K")
    p.add_argument("--pressure", type=float, default=101325, help="Pa")
    p.add_argument("--threads", type=int, default=4)
    p.add_argument("--memory", type=int, default=8000, help="MB for the whole process")
    a = p.parse_args()

    # thread pools are sized when numpy is imported, so this has to come first
    for var in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS"):
        os.environ[var] = str(a.threads)
    import numpy as np
    import pyscf
    from pyscf import dft, gto, lib
    from pyscf.geomopt import geometric_solver
    from pyscf.hessian import thermo

    if a.geom:
        atoms, comment = read_xyz(a.geom)
    else:
        atoms, comment = GEOMETRY, "inline geometry"
    mol = gto.M(atom=atoms, basis=a.basis, charge=a.charge, spin=a.mult - 1, unit="Angstrom",
                max_memory=a.memory, verbose=4)
    lib.num_threads(a.threads)
    workdir = os.path.dirname(os.path.abspath(a.out))   # optimized.xyz etc. go next to result.json
    result = {"program": "pyscf", "program_version": pyscf.__version__, "method": "dft",
              "basis": a.basis, "charge": a.charge, "multiplicity": a.mult, "task": "opt-freq",
              "geometry_file": os.path.abspath(a.geom) if a.geom else None, "geometry_comment": comment,
              "host": socket.gethostname(), "converged": False, "energies": {}}
    result["xc"] = a.xc

    def finish(converged, failure=None):
        """Write result.json (always) and exit with code 1 if something did not converge."""
        result["converged"] = bool(converged)
        if failure:
            result["failure"] = failure
        write_json(a.out, result)
        if not converged:
            sys.exit(failure or "not converged")

    def make_scf(mol):
        """Mean-field object with every setting of this job (reused at new geometries)."""
        mf = dft.RKS(mol, xc=a.xc)
        mf = mf.density_fit()   # density fitting (RI) for J and K, auxiliary basis chosen by PySCF
        mf.disp = "d3bj"   # needs pip install pyscf-dispersion
        mf.conv_tol = 1e-10
        mf.max_cycle = 200
        return mf

    t0 = time.perf_counter()
    mf = make_scf(mol)
    e_scf = mf.kernel()
    result["time_scf_s"] = time.perf_counter() - t0
    result["energies"]["scf"] = result["energies"]["total"] = float(e_scf)
    result["nbf"] = int(mol.nao_nr())
    result["nelectron"] = int(mol.nelectron)
    if not mf.converged:
        finish(False, "SCF did not converge")
    converged = True

    # geomeTRIC drives the optimization with analytic PySCF gradients
    t1 = time.perf_counter()
    opt_converged, mol = geometric_solver.kernel(mf, maxsteps=a.max_steps, convergence_set="GAU_TIGHT")
    result["time_opt_s"] = time.perf_counter() - t1
    result["optimization_converged"] = bool(opt_converged)
    write_xyz(os.path.join(workdir, "optimized.xyz"), mol, "optimized with PySCF/geomeTRIC")
    result["optimized_geometry_file"] = os.path.join(workdir, "optimized.xyz")
    mf = make_scf(mol)   # SCF at the final geometry (energy, Hessian)
    e_scf = mf.kernel()
    result["energies"]["scf"] = result["energies"]["total"] = float(e_scf)
    converged = bool(opt_converged) and mf.converged

    # analytic Hessian -> harmonic frequencies and RRHO thermochemistry
    t2 = time.perf_counter()
    hess = mf.Hessian().kernel()
    freq = thermo.harmonic_analysis(mf.mol, hess)
    th = thermo.thermo(mf, freq["freq_au"], a.temperature, a.pressure)
    thermo.dump_normal_mode(mf.mol, freq)
    thermo.dump_thermo(mf.mol, th)
    result["time_freq_s"] = time.perf_counter() - t2
    wn = np.asarray(freq["freq_wavenumber"])
    if np.iscomplexobj(wn):   # imaginary modes come back as imaginary numbers: store them as negative
        wn = np.where(np.abs(wn.imag) > 1e-8, -np.abs(wn.imag), wn.real)
    n_imag = int((wn < 0).sum())
    result["frequencies_cm1"] = wn.tolist()
    result["n_imaginary"] = n_imag
    result["thermo"] = {"temperature_K": a.temperature, "pressure_Pa": a.pressure,
                        "zpe_hartree": float(th["ZPE"][0]), "enthalpy_hartree": float(th["H_tot"][0]),
                        "gibbs_hartree": float(th["G_tot"][0])}
    result["is_minimum"] = n_imag == 0

    finish(converged, None if converged else "not all steps converged")


if __name__ == "__main__":
    main()
