#!/usr/bin/env python3
"""EOM-CCSD excitations

single point: EOM-CCSD (5 roots) on HF/aug-cc-pVDZ. Generated by Orbital Studio; edit freely.

  python run.py [geom.xyz] [result.json] [--nstates N] [--basis B] [--threads N] [--memory MB]

Without an .xyz argument the inline GEOMETRY below (Angstrom) is used.
result.json is written atomically, also when a step fails; the exit code is 1 if the SCF
or any later step did not converge.
Requires: pip install pyscf
"""
import argparse
import json
import os
import socket
import sys
import time

HARTREE_TO_EV = 27.211386245988

# Angstrom; used when no .xyz file is given on the command line
GEOMETRY = """
O       0.00000000     0.00000000     0.11730000
H       0.00000000     0.75720000    -0.46920000
H       0.00000000    -0.75720000    -0.46920000
"""


def write_json(path, data):
    with open(path + ".tmp", "w") as fh:
        json.dump(data, fh, indent=2)
    os.replace(path + ".tmp", path)   # atomic: a half-written result.json must never look done


def read_xyz(path):
    with open(path) as fh:
        lines = fh.read().splitlines()
    atoms = [(s, (float(x), float(y), float(z))) for s, x, y, z in
             (line.split()[:4] for line in lines[2:2 + int(lines[0])])]
    return atoms, lines[1].strip()


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("geom", nargs="?", default=None, help=".xyz file (Angstrom); default: the inline GEOMETRY")
    p.add_argument("out", nargs="?", default="result.json")
    p.add_argument("--basis", default="aug-cc-pVDZ")
    p.add_argument("--charge", type=int, default=0)
    p.add_argument("--mult", type=int, default=1, help="spin multiplicity 2S+1")
    p.add_argument("--nstates", type=int, default=5, help="number of excited states")
    p.add_argument("--triplets", action=argparse.BooleanOptionalAction, default=False, help="also compute triplet states")
    p.add_argument("--frozen-core", action=argparse.BooleanOptionalAction, default=True)
    p.add_argument("--threads", type=int, default=4)
    p.add_argument("--memory", type=int, default=16000, help="MB for the whole process")
    a = p.parse_args()

    # thread pools are sized when numpy is imported, so this has to come first
    for var in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS"):
        os.environ[var] = str(a.threads)
    import numpy as np
    import pyscf
    from pyscf import cc, gto, lib, scf
    from pyscf.data import elements
    from pyscf.cc import eom_rccsd

    if a.geom:
        atoms, comment = read_xyz(a.geom)
    else:
        atoms, comment = GEOMETRY, "inline geometry"
    mol = gto.M(atom=atoms, basis=a.basis, charge=a.charge, spin=a.mult - 1, unit="Angstrom",
                max_memory=a.memory, verbose=4)
    lib.num_threads(a.threads)
    result = {"program": "pyscf", "program_version": pyscf.__version__, "method": "eom-ee-ccsd",
              "basis": a.basis, "charge": a.charge, "multiplicity": a.mult, "task": "sp",
              "geometry_file": os.path.abspath(a.geom) if a.geom else None, "geometry_comment": comment,
              "host": socket.gethostname(), "converged": False, "energies": {}}

    def finish(converged, failure=None):
        """Write result.json (always) and exit with code 1 if something did not converge."""
        result["converged"] = bool(converged)
        if failure:
            result["failure"] = failure
        write_json(a.out, result)
        if not converged:
            sys.exit(failure or "not converged")

    def make_scf(mol):
        """Mean-field object with every setting of this job (reused at new geometries)."""
        mf = scf.RHF(mol)
        mf.conv_tol = 1e-10
        mf.max_cycle = 200
        return mf

    t0 = time.perf_counter()
    mf = make_scf(mol)
    e_scf = mf.kernel()
    result["time_scf_s"] = time.perf_counter() - t0
    result["energies"]["scf"] = result["energies"]["total"] = float(e_scf)
    result["nbf"] = int(mol.nao_nr())
    result["nelectron"] = int(mol.nelectron)
    if not mf.converged:
        finish(False, "SCF did not converge")
    converged = True

    ncore = elements.chemcore(mol) if a.frozen_core else None   # frozen core orbitals
    result["n_frozen_core_orbitals"] = int(ncore or 0)

    t1 = time.perf_counter()
    mycc = cc.CCSD(mf, frozen=ncore)
    mycc.kernel()
    result["time_ccsd_s"] = time.perf_counter() - t1
    result["energies"]["ccsd"] = result["energies"]["total"] = float(mycc.e_tot)
    if not mycc.converged:
        finish(False, "CCSD did not converge")

    # EOM-EE-CCSD singlets (PySCF gives no transition moments, so no oscillator strengths)
    t2 = time.perf_counter()
    eom = eom_rccsd.EOMEESinglet(mycc)
    e_exc, _ = eom.kernel(nroots=a.nstates)
    root_conv = [bool(c) for c in np.atleast_1d(eom.converged)]
    result["excitation_energies_ev"] = (np.atleast_1d(e_exc) * HARTREE_TO_EV).tolist()
    result["roots_converged"] = root_conv
    converged = converged and all(root_conv)
    if a.triplets:
        eom_t = eom_rccsd.EOMEETriplet(mycc)
        e_t, _ = eom_t.kernel(nroots=a.nstates)
        result["triplet_excitation_energies_ev"] = (np.atleast_1d(e_t) * HARTREE_TO_EV).tolist()
        converged = converged and all(np.atleast_1d(eom_t.converged))
    result["time_adc_s"] = result["time_excited_s"] = time.perf_counter() - t2   # time_adc_s: read by the Calculations tab
    for i, e in enumerate(result["excitation_energies_ev"], 1):
        print(f"state {i}: {e:10.6f} eV ({1239.841984 / e:7.2f} nm)")

    finish(converged, None if converged else "not all steps converged")


if __name__ == "__main__":
    main()
